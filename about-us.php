   function updateTimelineProgress(currentSlide) {

    var timeline = $(".journey-timeline")[0];
    var items = $(".journey-timeline-item");

    if (!timeline || !items.length) {
        return;
    }

    var timelineRect = timeline.getBoundingClientRect();

    var activeItem = items.filter(
        '[data-slide="' + currentSlide + '"]'
    )[0];

    if (!activeItem) {
        return;
    }

    var activeRect = activeItem.getBoundingClientRect();

    var progressWidth =
        (activeRect.left + (activeRect.width / 2)) -
        timelineRect.left;

    /*
     * Last slide par line ko exactly
     * timeline ke end tak complete karo
     */
    if (currentSlide === items.length - 1) {
        progressWidth = timelineRect.width;
    }

    progressWidth = Math.max(
        0,
        Math.min(progressWidth, timelineRect.width)
    );

    $(".journey-timeline").css(
        "--timeline-progress",
        progressWidth + "px"
    );

    items.removeClass("active");
    $(activeItem).addClass("active");
}


    /* =========================================
       SLIDE CHANGE
    ========================================= */

    $(".journey-sync-content").on(
        "afterChange",
        function (event, slick, currentSlide) {

            updateTimelineProgress(currentSlide);

        }
    );


    /* =========================================
       INITIAL STATE
    ========================================= */

    updateTimelineProgress(0);


    /* =========================================
       UPDATE ON RESIZE
    ========================================= */

    $(window).on("resize", function () {

        var currentSlide =
            $(".journey-sync-content").slick("slickCurrentSlide");

        updateTimelineProgress(currentSlide);

    });

});
